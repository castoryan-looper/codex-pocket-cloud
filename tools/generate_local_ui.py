"""Bake Chinese local feedback into firmware; no network/font runtime dependency."""
from pathlib import Path
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = os.environ.get('POCKET_FONT') or next(str(p) for p in (
    Path('C:/Windows/Fonts/msyh.ttc'),
    Path('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc')) if p.exists())

SCREENS = [
    ('按住 BOOT', '满 1 秒开始录音', '提前松开：短按确认'),
    ('正在录音', '请说话，松开 BOOT 结束', 'PWR 取消 / 双键3秒配网'),
    ('录音已结束', '正在上传音频', '无需再按键，请稍候'),
    ('正在识别', '录音已提交云端', '识别后先确认，再发送任务'),
    ('录音太短', '看到“正在录音”后再说话', '重新按住 BOOT 1 秒'),
    ('录音未完成', '麦克风或网络传输中断', '重新按住 BOOT 1 秒重试'),
    ('录音已取消', '本次音频不会提交识别', '按住 BOOT 1 秒重新录音'),
    ('已达录音上限', '请松开 BOOT', '松开后查看识别结果'),
    ('Wi-Fi 未连接', '请开启 2.4GHz 手机热点', '双键长按 3 秒：网络配置'),
    ('云端未连接', 'Wi-Fi 已连接，正在重试', '双键长按 3 秒：查看配置'),
    ('尚未配置服务', '请导入云端连接 JSON', '双键长按 3 秒：打开配置'),
    ('等待云端确认', '加密通道已连接', '正在等待服务状态画面'),
]


def label(draw, xy, text, size):
    draw.text(xy, text, font=ImageFont.truetype(FONT, size), fill=0)


def main():
    images = []
    for index, (title, detail, footer) in enumerate(SCREENS):
        im = Image.new('1', (200, 200), 1)
        d = ImageDraw.Draw(im)
        d.line((6, 25, 194, 25), fill=0)
        label(d, (8, 35), title, 23 if len(title) < 8 else 21)
        label(d, (8, 76), detail, 13)
        if index == 0:
            label(d, (74, 102), '1s', 38)
        if index == 1:
            for x, height in zip(range(65, 140, 12), (8, 18, 28, 36, 28, 18, 8)):
                d.rectangle((x, 157-height//2, x+5, 157), fill=0)
        d.line((6, 166, 194, 166), fill=0)
        label(d, (8, 175), footer, 12)
        images.append(im)
    lines = ['#pragma once', '#include <stdint.h>', '// Generated by tools/generate_local_ui.py. One-bit, 200x200, MSB first.',
             'static const uint8_t localScreens[][5000] = {']
    for im in images:
        data = im.tobytes()
        assert len(data) == 5000
        lines.append('{' + ','.join(f'0x{x:02x}' for x in data) + '},')
    lines.append('};')
    auto = images[3].copy()
    draw = ImageDraw.Draw(auto)
    draw.rectangle((0, 169, 199, 199), fill=1)
    label(draw, (8, 175), '识别后自动发送', 12)
    lines.append('static const uint8_t localAutoRecognizing[5000] = {' + ','.join(f'0x{x:02x}' for x in auto.tobytes()) + '};')
    for name, title in [('Online', '云端在线'), ('Offline', '云端离线'), ('Connecting', '连接云端中')]:
        im = Image.new('1', (80, 25), 1)
        label(ImageDraw.Draw(im), (5, 4), title, 13)
        lines.append(f'static const uint8_t localHeader{name}[250] = {{' + ','.join(f'0x{x:02x}' for x in im.tobytes()) + '};')
    footer = Image.new('1', (200, 14), 1)
    label(ImageDraw.Draw(footer), (6, 0), 'BOOT 确认 / 按住1秒录音', 11)
    lines.append('static const uint8_t localFooter[350] = {' + ','.join(f'0x{x:02x}' for x in footer.tobytes()) + '};')
    for name, message in [('Boot', 'BOOT 已按下，等待响应'), ('Power', 'PWR 已按下，等待响应')]:
        im = Image.new('1', (200, 14), 1)
        label(ImageDraw.Draw(im), (6, 0), message, 11)
        lines.append(f'static const uint8_t localFooter{name}[350] = {{' + ','.join(f'0x{x:02x}' for x in im.tobytes()) + '};')
    (ROOT/'firmware/Pocket/local_ui.h').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    preview = Image.new('1', (800, 600), 1)
    for index, im in enumerate(images):
        preview.paste(im, ((index % 4)*200, (index // 4)*200))
    return preview


if __name__ == '__main__':
    main()
