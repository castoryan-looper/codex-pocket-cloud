"""Bake transport-specific setup screens; dynamic URLs are drawn by firmware."""
from pathlib import Path
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = os.environ.get('POCKET_FONT', 'C:/Windows/Fonts/msyh.ttc')


def screens():
    result = {}
    for mode in ('Usb', 'Ap'):
        im = Image.new('1', (200, 200), 1)
        draw = ImageDraw.Draw(im)
        def text(x, y, label, size):
            draw.text((x, y), label, font=ImageFont.truetype(FONT, size), fill=0)
        text(8, 4, '设备配置', 13)
        draw.line((6, 25, 194, 25), fill=0)
        text(8, 36, 'USB 配置' if mode == 'Usb' else 'Wi-Fi 热点配置', 21)
        if mode == 'Usb':
            text(8, 74, '在已连接电脑的浏览器打开', 12)
            text(8, 132, 'Chrome / Edge 连接 USB', 12)
            text(8, 150, '刷机前请在网页断开连接', 12)
        else:
            text(8, 72, '连接下方热点，再打开管理页', 12)
        draw.line((6, 168, 194, 168), fill=0)
        text(8, 179, 'PWR 长按退出配置', 12)
        result[mode] = im
    return result


if __name__ == '__main__':
    images = screens()
    content = ['#pragma once', '#include <stdint.h>', '// Generated by tools/generate_config_screens.py.']
    for name, im in images.items():
        content.append(f'static const uint8_t config{name}Screen[5000] = {{' + ','.join(f'0x{v:02x}' for v in im.tobytes()) + '};')
    (ROOT/'firmware/Pocket/config_screens.h').write_text('\n'.join(content)+'\n', encoding='utf-8', newline='\n')
